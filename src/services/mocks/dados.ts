const hoje = new Date();

function diasAtras(amount: number): string {
  return paraDataISO(somarDias(hoje, -amount));
}

function diaDoMes(offset: number, day: number): string {
  return `${chaveMesPorDeslocamento(offset)}-${String(day).padStart(2, '0')}`;
}

