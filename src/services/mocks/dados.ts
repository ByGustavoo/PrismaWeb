export function listarOrigens(): OrigemDTO[] {
  return [
    ...contas
      .filter((account) => account.situacao === 'ATIVO')
      .map((account) => ({ id: account.id, nome: account.nome, grupo: 'CONTA' as const })),
    ...cartoes
      .filter((card) => card.situacao === 'ATIVO' && card.tipo !== 'DEBITO')
      .map((card) => ({ id: card.id, nome: card.nome, grupo: 'CARTAO' as const })),
  ];
}

export function buscarOrigem(id: string): OrigemDTO | undefined {
  const account = contas.find((item) => item.id === id);
  if (account) return { id: account.id, nome: account.nome, grupo: 'CONTA' };

  const card = cartoes.find((item) => item.id === id);
  return card ? { id: card.id, nome: card.nome, grupo: 'CARTAO' } : undefined;
}

