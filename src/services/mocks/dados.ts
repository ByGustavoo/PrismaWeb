const mesesFreelance: Record<number, number> = {
  1: 2400,
  3: 3100,
  5: 1750,
  8: 2650,
  11: 1980,
  14: 2300,
  17: 2050,
};

function montarHistorico(): LancamentoDTO[] {
  const result: LancamentoDTO[] = [];
  const todayDay = hoje.getDate();

  for (let offset = 0; offset < variacaoMensal.length; offset += 1) {
    const month = chaveMesPorDeslocamento(-offset);
    const variation = variacaoMensal[offset] ?? 1;

    for (const [index, entry] of modeloMensal.entries()) {
      if (offset === 0 && entry.dia > todayDay) continue;

      const { dia, fixo, ...rest } = entry;
      result.push({
        ...rest,
        id: `tx-h${offset}-${String(index + 1).padStart(2, '0')}`,
        data: `${month}-${String(dia).padStart(2, '0')}`,
        situacao: 'PAGO',
        valor: fixo ? rest.valor : Math.round(rest.valor * variation * 100) / 100,
      });
    }

    const freelance = mesesFreelance[offset];
    if (freelance && !(offset === 0 && todayDay < 21)) {
      result.push({
        id: `tx-h${offset}-freela`,
        descricao: 'Projeto freelance',
        valor: freelance,
        tipo: 'RECEITA',
        situacao: 'PAGO',
        forma: 'PIX',
        data: `${month}-21`,
        categoria: categoria.freelance,
        idOrigem: 'acc-1',
        nomeOrigem: 'Conta corrente',
      });
    }
  }

  return result;
}

lancamentos.push(...montarHistorico());
